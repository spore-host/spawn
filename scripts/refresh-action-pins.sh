#!/usr/bin/env bash
# Regenerate scripts/action-pins.txt: the version tag each SHA-pinned action in
# .github/workflows actually resolves to, read from GitHub rather than from the
# `# vX.Y.Z` comment beside the pin. workflow_pins_test.go checks every pin's
# comment against this table offline, so a comment that misstates its SHA (the
# `actions/checkout@3d3c42e… # v6` that was really v7.0.1) fails a test.
#
#   scripts/refresh-action-pins.sh          rewrite the table
#   scripts/refresh-action-pins.sh --check  exit 1 if the committed table is stale
#
# Run it after any change to a `uses:` pin (including a Dependabot bump) and
# commit the result. Needs an authenticated `gh`; reads only, creates nothing.
set -euo pipefail

cd "$(dirname "$0")/.."
table=scripts/action-pins.txt
mode=${1:-write}

shopt -s nullglob
workflows=(.github/workflows/*.yml .github/workflows/*.yaml)
if [ ${#workflows[@]} -eq 0 ]; then
  echo "no workflows under .github/workflows — discovery has broken" >&2
  exit 1
fi

# owner/repo and SHA of every pinned remote action, deduplicated. An action in a
# subdirectory (owner/repo/path@sha) lives in owner/repo, so that is the key.
pins=$(sed -nE 's/^[[:space:]]*(-[[:space:]]+)?uses:[[:space:]]*([^/@[:space:]]+\/[^/@[:space:]]+)[^@[:space:]]*@([0-9a-f]{40}).*/\2 \3/p' \
  "${workflows[@]}" | sort -u)
if [ -z "$pins" ]; then
  echo "found no SHA-pinned actions in ${workflows[*]} — discovery has broken" >&2
  exit 1
fi

# resolve REPO SHA: the highest vX.Y.Z tag whose commit is SHA. Annotated tags
# point at a tag object, not the commit, so those are dereferenced — comparing
# the tag object's SHA would match nothing and report every pin as unknown.
resolve() {
  local repo=$1 sha=$2 ref typ obj
  gh api "repos/$repo/git/matching-refs/tags/v" --paginate \
    --jq '.[] | "\(.ref) \(.object.type) \(.object.sha)"' </dev/null |
  while read -r ref typ obj; do
    ref=${ref#refs/tags/}
    [[ $ref =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || continue
    if [ "$typ" = tag ]; then
      obj=$(gh api "repos/$repo/git/tags/$obj" --jq .object.sha </dev/null)
    fi
    if [ "$obj" = "$sha" ]; then echo "$ref"; fi
  done | sort -V | tail -1
}

out=$(mktemp)
trap 'rm -f "$out"' EXIT
{
  echo "# Generated by scripts/refresh-action-pins.sh — do not edit by hand."
  echo "# <owner/repo> <commit SHA> <the vX.Y.Z tag that SHA is, per GitHub>"
  while read -r repo sha; do
    tag=$(resolve "$repo" "$sha")
    if [ -z "$tag" ]; then
      echo "$repo@$sha is not the commit of any vX.Y.Z tag; pin a released version" >&2
      exit 1
    fi
    echo "$repo $sha $tag"
  done <<<"$pins"
} >"$out"

if [ "$mode" = --check ]; then
  if ! diff -u "$table" "$out"; then
    echo "$table is stale — run scripts/refresh-action-pins.sh and commit it" >&2
    exit 1
  fi
  echo "✓ $table matches GitHub"
else
  cp "$out" "$table"
  echo "wrote $table ($(grep -vc '^#' "$table") pins)"
fi
