// GenerateWrapper builds the self-contained bash script that runs one task on
// its ephemeral instance. It is assigned to aws.LaunchConfig.JobArrayCommand, so
// launcher.Provision embeds it as /etc/spawn/command → /tmp/spawn-command.sh.
// This wrapper IS the reference implementation of the task-execution protocol's
// on-instance contract: stage inputs, run the command, stage outputs, and write
// the durable completion record to S3 — regardless of whether the command
// succeeds.
//
// resultsBucket is the plain bucket name (no s3:// prefix); the record lands
// under tasks/<task_id>/ in it. region is used only for the ECR login of a
// private-registry container image.
//
// Design notes (also commented in the emitted script):
//   - We do NOT `set -e`. Under -e the script would abort the instant the user
//     command exits non-zero, so stage-out and the completion record would never
//     run — defeating the purpose. We capture rc=$? explicitly and gate the rest.
//   - The user command is argv ([]string); each element is single-quoted and run
//     in a subshell (host) or as the container's argv so there is no shell
//     re-parse of a joined string.
//   - Every interpolated value (command args, env values, paths, task_id, image,
//     mount dirs) is single-quoted via shQuote. Env keys are validated in Validate.
//   - When spec.Container is set, the command runs inside that image via `docker
//     run` with the manifest dirs bind-mounted; stage-in/out still happen on the
//     host, so the image needs no aws CLI. Docker is installed on demand.
//
// The per-launch inputs (results prefix, run id, region, GPU) arrive in a
// WrapperOptions; see its doc for why they are not positional (spawn#764).
// Returns an error rather than a script when a required option is missing, so a
// forgotten field fails loudly here instead of emitting an unattributable
// completion record discovered weeks later.
func GenerateWrapper(spec *TaskSpec, opts WrapperOptions) (string, error) {
	if err := opts.Validate(); err != nil {
		return "", err
	}
	return generateWrapper(spec, opts.ResultsPrefix, opts.Region, true, opts.GPU, opts.RunID), nil
}

// GeneratePooledJobScript builds the per-job script a POOLED worker runs for one
// task (#70). It is byte-for-byte GenerateWrapper EXCEPT it omits the final
// /tmp/SPAWN_COMPLETE signal: that file drives spored's on_complete action
// (terminate/stop), which is correct for a one-instance-per-task launch but fatal
// for a pooled worker — it would self-terminate after its FIRST task and defeat
// reuse. The worker stays alive and keeps pulling; it drains on idle-timeout
// instead. The durable completion record (completion.json + .exitcode) is still
// written, so the submitter's poll is unchanged.
//
// opts.RunID is stamped into that record exactly as in GenerateWrapper
// (spawn#608): a pooled worker overwrites the same tasks/<task_id>/completion.json
// key on every execution of a given task_id, so its records need attempt identity
// for the same reason the one-instance path does. The pooled dispatcher has no
// launch-side id to hand down (it runs on an already-provisioned worker), so
// ScriptExecer mints one per execution — see pkg/taskpool/exec.go.
func GeneratePooledJobScript(spec *TaskSpec, opts WrapperOptions) (string, error) {
	if err := opts.Validate(); err != nil {
		return "", err
	}
	return generateWrapper(spec, opts.ResultsPrefix, opts.Region, false, opts.GPU, opts.RunID), nil
}

// generateWrapper is the shared body. signalComplete gates the spored
// self-terminate signal: true for the one-instance-per-task wrapper, false for a
// pooled worker's per-job script. gpu gates GPU-container setup (--gpus all +
// NVIDIA Container Toolkit install). runID is stamped into the completion record
// (spawn#608).
func generateWrapper(spec *TaskSpec, resultsPrefix, region string, signalComplete, gpu bool, runID string) string {
	var b strings.Builder
	p := func(format string, a ...interface{}) { fmt.Fprintf(&b, format, a...) }

	taskID := spec.TaskID
	// resultsPrefix arrives already resolved (EffectiveResultsPrefix) rather than
	// being derived here, so a spec's results_prefix override reaches the wrapper,
	// the flush hook and the policy from ONE place (spawn#646).

	p("#!/bin/bash\n")
	p("# spawn task wrapper — task_id=%s (generated by 'spawn task run', spawn#386)\n", taskID)
	p("# NOTE: intentionally not 'set -e' — we must survive a failing user command\n")
	p("# to still stage outputs and write the durable completion record.\n")
	// `set +e` is explicit, not a no-op default (spawn#566): this text is not
	// always run as its own bash process. pkg/launcher/bootstrap.go writes it
	// (via /etc/spawn/command) verbatim into the TAIL of /tmp/spawn-command.sh,
	// whose own preamble is `#!/bin/bash\nset -e\n...` — the two are concatenated
	// into ONE script file and executed as a single bash invocation, not two. A
	// shell option set early in a script stays in effect for the rest of that
	// same script, so without an explicit `+e` here this text silently inherited
	// `-e` from that preamble despite the comment above: a failing `docker run`
	// (or the host command's subshell) aborted the WHOLE script right there —
	// before `rc=$?` was ever reached — so stage-out, classification, and the
	// completion-record write never ran. That is exactly the field-reported
	// symptom: a failed task with NO completion record at all, riding to TTL
	// instead of self-terminating. Reproduced locally by concatenating this
	// generated script after bootstrap.go's literal `set -e` preamble and running
	// the result with a stand-in `docker` that exits non-zero: completion.json /
	// .exitcode / SPAWN_COMPLETE were never written until this `set +e` was
	// added. Setting it here makes the script correct regardless of whatever
	// shell option state the embedding caller left behind, rather than relying
	// on every embedder to never set -e upstream of it.
	p("set +e -u -o pipefail\n\n")

	p("RESULTS_PREFIX=%s\n", shQuote(resultsPrefix))
	p("STARTED_AT=\"$(date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ)\"\n")
	// Persist STARTED_AT where the terminal-flush hook can read it (spawn#632).
	// That hook runs as a separate root process while this wrapper is still blocked
	// on the user's command, so it cannot see this shell's variables; without the
	// file, a record flushed by a TTL kill would have to either omit started_at or
	// invent one. Best-effort — losing it costs one field, not the record.
	p("printf '%%s' \"$STARTED_AT\" > %s 2>/dev/null || true\n", shQuote(StartedAtPath()))
	writeInstanceFacts(p)
	writeProvenanceSetup(p, spec, runID)
	// Phase markers. completion.json carries only started_at/ended_at, so the
	// whole interval between them — stage-in, the Docker install, the image pull,
	// the user command, stage-out — is one opaque number. Measured on a real task
	// (cookbook-relion-postprocess-r1): a 94s window of which the user command was
	// 25s, with no way to attribute the other ~69s. These lines make command.log
	// self-timing at the cost of one `date` per phase. Deliberately plain text on
	// stdout rather than a second structured artifact: nothing parses command.log
	// (cmd/service.go's readiness grep is the service path, not this wrapper), and
	// a log a human can read is the thing that was missing.
	//
	// Milliseconds (#1072): a 1 s stamp could not time the short phases, such as
	// a 3.8-4.5 s container start. %3N is GNU date (AL2023's coreutils). Only
	// these markers change: started_at/ended_at in completion.json keep their
	// whole-second form, which adapters and the cost estimate parse.
	p("spawn_phase() { echo \"spawn: [$(date -u %s)] $*\"; }\n", PhaseTimestampFormat)
	p("spawn_phase 'wrapper start'\n\n")

	// ---- env ----
	if len(spec.Env) > 0 {
		p("# ---- task environment ----\n")
		for _, k := range sortedKeys(spec.Env) {
			p("export %s=%s\n", k, shQuote(spec.Env[k]))
		}
		p("\n")
	}

	// ---- container runtime install, overlapping stage-in ----
	if spec.Container != "" {
		writeDockerInstallStart(p)
	}

	// ---- stage-in ----
	p("# ---- stage-in ----\n")
	p("spawn_phase 'stage-in start'\n")
	p("STAGE_RC=0\n")
	// mkdir -p every directory manifestMountDirs will bind-mount (spawn#564):
	// input Destination parents AND output Source parents, from the SAME set
	// `docker run -v` mounts for those manifest entries. Pre-creating them here,
	// as the invoking user, means `docker run` never gets the chance to
	// auto-create a missing bind-mount source itself — which it does as root,
	// mode 0755, leaving the non-root container unable to write into it.
	// Reusing manifestMountDirs' output (rather than recomputing "what needs a
	// mkdir" separately from "what gets mounted") keeps the two lists from
	// drifting apart again.
	//
	// Deliberately NOT containerMountDirs (spawn#570): that function ALSO
	// includes Placement's EFS/FSx/volume mount points, which this loop must
	// NOT mkdir. Those paths are mounted onto by the boot-time storage script
	// (pkg/tasklaunch's taskStorageScript, which runs before this wrapper) —
	// mkdir -p on top of an already-live NFS/Lustre mount is a harmless no-op,
	// but mkdir -p BEFORE that mount lands would create a plain local directory
	// at the mount point, which the later mount then shadows: any file this
	// script writes into it while racing the mount lands on the local disk, not
	// the shared filesystem, and silently disappears from the container's/host's
	// view once the mount completes. Placement mount points must appear in the
	// docker-mount set without ever appearing in this mkdir set.
	// sudo, and only for a directory that does not already exist (spawn#564).
	//
	// A plain `mkdir -p` here ran as the unprivileged instance user, so it could
	// not create any directory whose parent it does not own — which includes every
	// top-level path: /out, /data, /work. Confirmed on a real t4g.medium, which is
	// the only way this shows up (a code read sees the mkdir emitted and concludes
	// it works):
	//
	//	mkdir: cannot create directory ‘/out’: Permission denied
	//	spawn: [...] stage-in done rc=0              <- failure swallowed
	//	drwxr-xr-x 2 0 0 /out/results                <- docker -v made it, as root
	//	sh: can't create /out/results/a.txt: Permission denied
	//
	// So the very auto-creation-as-root this loop exists to prevent happened
	// anyway, 90 seconds later, surfacing as a container permission error with no
	// hint that a host mkdir had failed. spawn's own documented /data + /work
	// example could not work, and /tmp was the only usable staging location
	// (it already exists, 1777) — which is what forced callers to keep every
	// staged path flat in /tmp.
	//
	// The existence test is not an optimization, it is required: chown'ing a
	// PRE-EXISTING directory would be destructive. A destination of
	// /tmp/staged.bin yields a mount dir of /tmp, and `chown` on that would strip
	// the sticky 1777 ownership /tmp needs for every other user on the box.
	// Only directories this script actually creates get their ownership set.
	//
	// A failure now sets STAGE_RC so the task fails AT stage-in, classified
	// staging_error, instead of running the command against an unwritable mount.
	// Unprivileged mkdir first, escalating to sudo only when that fails. Where the
	// parent is already writable (/tmp/sub, a path under $HOME) the directory is
	// created by the invoking user and is therefore already owned by it, so no
	// chown is needed and no privilege is used. sudo is the fallback for a
	// top-level path, and the chown is what makes the root-created directory
	// writable by the container.
	for _, dir := range manifestMountDirs(spec) {
		q := shQuote(dir)
		p("if [ ! -d %s ]; then\n", q)
		p("  if mkdir -p %s 2>/dev/null; then\n", q)
		p("    :\n")
		p("  elif sudo mkdir -p %s && sudo chown \"$(id -u):$(id -g)\" %s; then\n", q, q)
		p("    :\n")
		p("  else\n")
		p("    echo 'spawn: cannot create mount dir %s' >&2\n", dir)
		p("    STAGE_RC=1\n")
		p("  fi\n")
		p("fi\n")
	}
	p("\n")
	for _, m := range spec.Inputs {
		p("if [ \"$STAGE_RC\" -eq 0 ]; then\n")
		p("  %s%s %s %s || STAGE_RC=$?\n", s3Cp, recursiveFlag(m.Source), shQuote(m.Source), shQuote(m.Destination))
		// chown the staged path to the invoking uid:gid right after it lands
		// (spawn#565). Host /tmp is 1777 (sticky): a container that later needs
		// to unlink a staged file may only do so if it OWNS THAT FILE — sharing
		// the directory's uid is not enough under the sticky bit. `aws s3 cp`
		// already runs as the invoking user here, so today this chown is a
		// same-uid no-op in every real call site — it's still emitted
		// unconditionally (not gated on spec.Container) so the invariant
		// "staged files are owned by the uid the container will run as" holds
		// by construction, not by the accident of stage-in and `docker run
		// --user "$(id -u):$(id -g)"` sharing one uninterrupted shell session.
		// Uses the SAME "$(id -u):$(id -g)" that --user passes (#555), so the
		// two can never drift apart. -R for a prefix source (aws s3 cp
		// --recursive populated a whole tree under Destination, not just
		// Destination itself).
		//
		// sudo, not plain chown: a non-root chown can only reassign a file to
		// a uid that ALREADY owns it (verified: `chown` as an unprivileged
		// user to any other uid fails EPERM even for your own file) — so a
		// plain chown here would be a no-op in the case it already matches and
		// silently do nothing in the one case it would need to actually repair
		// a mismatch, defeating the whole point of a defense-in-depth guard.
		// sudo is available: bootstrap.go grants the instance user passwordless
		// sudo, the same precondition writeContainerRun already relies on for
		// every docker/dnf call. Best-effort (|| true): the same-uid case
		// (today, always) can never fail, and if ownership genuinely can't be
		// fixed even as root, the container will surface that itself when it
		// tries to write.
		p("  sudo chown%s \"$(id -u):$(id -g)\" %s 2>/dev/null || true\n", recursiveChownFlag(m.Source), shQuote(m.Destination))
		p("fi\n")
	}
	p("spawn_phase \"stage-in done rc=$STAGE_RC\"\n")
	// Record each input as it was read (#1076): the ETag/version a later
	// deletion sweeper compares against. Never affects the task.
	p("if [ \"$PROV_OK\" = 1 ] && [ \"$STAGE_RC\" -eq 0 ]; then\n")
	p("  \"$SPORED\" provenance stage-in --spec \"$PROV_DIR/spec.json\" --state \"$PROV_DIR\" >/dev/null 2>&1 || true\n")
	p("fi\n")
	p("\n")

	// ---- run user command ----
	p("# ---- run user command ----\n")
	p("rc=0\n")
	// RUNTIME_RC: the host could not provide the container runtime (Docker
	// install, daemon start). Set only by writeContainerRun; declared here so the
	// classifier below reads a defined variable under `set -u` on the host path.
	p("RUNTIME_RC=0\n")
	p("if [ \"$STAGE_RC\" -eq 0 ]; then\n")
	if spec.Container != "" {
		writeContainerRun(p, spec, region, gpu)
	} else {
		// Host path: run argv in a subshell (no shell re-parse of a joined string).
		p("  spawn_phase 'command start'\n")
		p("  ( %s )\n", quoteArgv(spec.Command))
		p("  rc=$?\n")
		p("  spawn_phase \"command exit rc=$rc\"\n")
	}
	p("else\n")
	p("  echo 'spawn: stage-in failed; skipping user command' >&2\n")
	if spec.Container != "" {
		// Never leave the background install running: a pooled worker's next job
		// would collide with its dnf lock, and a test would leave a child behind.
		p("  wait \"$DOCKER_INSTALL_PID\" 2>/dev/null || true\n")
		p("  rm -f \"$DOCKER_INSTALL_LOG\"\n")
	}
	p("  rc=$STAGE_RC\n")
	p("fi\n")
	p("ENDED_AT=\"$(date -u +%%Y-%%m-%%dT%%H:%%M:%%SZ)\"\n\n")
	// The run's cost and the provenance record (#1076). COST_USD is a number or
	// empty; anything else is discarded so completion.json stays valid JSON.
	p("COST_USD=''\n")
	p("if [ \"$PROV_OK\" = 1 ]; then\n")
	p("  COST_USD=\"$(SPAWN_RUN_ID=%s \"$SPORED\" provenance cost --spec \"$PROV_DIR/spec.json\" --state \"$PROV_DIR\" --started \"$STARTED_AT\" --ended \"$ENDED_AT\" 2>/dev/null)\" || COST_USD=''\n", shQuote(runID))
	p("fi\n")
	p("case \"$COST_USD\" in ''|*[!0-9.]*) COST_USD='' ;; esac\n\n")

	// ---- stage-out (only when the command actually ran; runs even if it failed) ----
	p("# ---- stage-out (runs even when the user command failed) ----\n")
	p("OUT_RC=0\n")
	if len(spec.Outputs) > 0 {
		p("if [ \"$STAGE_RC\" -eq 0 ]; then\n")
		p("  spawn_phase 'stage-out start'\n")
		for _, m := range spec.Outputs {
			// spored uploads exactly where `aws s3 cp` would, with the provenance
			// tags set in the same request and the record annotated (#1076). Without
			// a spored that has the subcommand, it's plain `aws s3 cp`, as before.
			//
			// If spored's upload fails for ANY reason, the output still goes up with
			// plain `aws s3 cp`, untagged, and untagged means kept. Provenance must
			// never cost a researcher their output: on v0.132.0 spored's S3 client
			// had no region on an instance (#1094), and with no fallback every task
			// output was lost as output_delivery_error.
			cp := fmt.Sprintf("%s%s %s %s", s3Cp, recursiveFlag(m.Source), shQuote(m.Source), shQuote(m.Destination))
			p("  if [ \"$PROV_OK\" = 1 ]; then\n")
			p("    if ! \"$SPORED\" provenance upload --state \"$PROV_DIR\" %s %s; then\n", shQuote(m.Source), shQuote(m.Destination))
			p("      spawn_phase 'provenance upload failed; uploading untagged with aws s3 cp'\n")
			p("      %s || OUT_RC=$?\n", cp)
			p("    fi\n")
			p("  else\n")
			p("    %s || OUT_RC=$?\n", cp)
			p("  fi\n")
		}
		p("  spawn_phase \"stage-out done rc=$OUT_RC\"\n")
		p("fi\n")
	}
	p("\n")

	// ---- classification + durable completion record ----
	p("# ---- classify + write the durable completion record ----\n")
	// state and retry_class are decided from STAGE_RC / rc / OUT_RC, in that
	// priority order (spawn#561): STAGE_RC means nothing ran at all; rc means the
	// user's command itself failed; only when BOTH of those are clean does OUT_RC
	// get to fail the task — that is the "compute succeeded, delivery failed"
	// case, which is why it gets its own retry class (RetryOutputDeliveryError)
	// rather than reusing RetryStagingError or RetryAppError. Before this, OUT_RC
	// was computed above and never read anywhere: a stage-out failure left
	// STATE=completed/exit_code=0/retry_class="" even though a declared output
	// never reached its destination.
	//
	// RUNTIME_RC sits between STAGE_RC and rc (#1180): when Docker could not be
	// installed or its daemon never came up, the user's command never ran, so
	// the non-zero rc is the host's failure, not the application's. On a
	// t4g.nano `dnf install docker` is OOM-killed; that used to surface as
	// `docker: command not found` from the run line and be classified app_error,
	// telling an adapter not to retry an infrastructure failure.
	p("if [ \"$STAGE_RC\" -ne 0 ]; then\n")
	p("  STATE='failed'; RETRY_CLASS='%s'\n", RetryStagingError)
	p("elif [ \"$RUNTIME_RC\" -ne 0 ]; then\n")
	p("  STATE='failed'; RETRY_CLASS='%s'\n", RetryInstanceHealth)
	p("elif [ \"$rc\" -ne 0 ]; then\n")
	p("  STATE='failed'; RETRY_CLASS='%s'\n", RetryAppError)
	p("elif [ \"$OUT_RC\" -ne 0 ]; then\n")
	p("  STATE='failed'; RETRY_CLASS='%s'\n", RetryOutputDeliveryError)
	p("else\n")
	p("  STATE='completed'; RETRY_CLASS=''\n")
	p("fi\n\n")

	// Best-effort copy of the command log; populates logs[] when it succeeds.
	p("LOGS_JSON='[]'\n")
	p("if %s /var/log/spawn-command.log \"$RESULTS_PREFIX/command.log\"; then\n", s3Cp)
	p("  LOGS_JSON=\"[\\\"$RESULTS_PREFIX/command.log\\\"]\"\n")
	p("fi\n\n")

	// completion.json — the authoritative record. Built with a heredoc; all
	// interpolated values are either shell ints (rc) or our own controlled strings.
	// cost_estimate (#1076): present only when the rate was known.
	p("COST_JSON=''\n")
	p("if [ -n \"$COST_USD\" ]; then COST_JSON=\"\\\"cost_estimate\\\": $COST_USD,\"; fi\n")
	p("cat > %s <<JSON\n", shQuote(CompletionRecordPath()))
	p("{\n")
	p("  \"task_id\": %s,\n", jsonStr(taskID))
	// run_id — the attempt identity (spawn#608). Emitted unconditionally (even
	// when empty) so the shape of the record is the same for every run and a
	// reader can distinguish "this wrapper stamps run ids and this one was
	// unattributed" from "this record predates run-id stamping" only by the value,
	// never by a structurally different record. `spawn task run --wait` compares
	// it to the id it launched with and keeps polling on a mismatch, so a record
	// left behind by a previous attempt of the same task_id can never be reported
	// as this run's verdict.
	p("  \"run_id\": %s,\n", jsonStr(runID))
	p("  \"exit_code\": $rc,\n")
	p("  \"state\": \"$STATE\",\n")
	p("  \"started_at\": \"$STARTED_AT\",\n")
	p("  \"ended_at\": \"$ENDED_AT\",\n")
	p("  $COST_JSON\n")
	p("  $INSTANCE_JSON\n")
	p("  \"logs\": $LOGS_JSON,\n")
	p("  \"retry_class\": \"$RETRY_CLASS\"\n")
	p("}\n")
	p("JSON\n")
	p("%s %s \"$RESULTS_PREFIX/completion.json\" || true\n\n", s3Cp, shQuote(CompletionRecordPath()))

	// .exitcode — the plain-integer legacy signal the RFC names.
	p("printf '%%s' \"$rc\" > %s\n", shQuote(localPath(exitCodeFileName)))
	p("%s %s \"$RESULTS_PREFIX/.exitcode\" || true\n\n", s3Cp, shQuote(localPath(exitCodeFileName)))

	// ---- signal spored ---- so on_complete fires and `spawn status --check-complete` works.
	// A pooled worker (signalComplete=false) SKIPS this: writing SPAWN_COMPLETE would
	// trigger spored's on_complete (terminate/stop) after the FIRST task, killing the
	// worker and defeating reuse. The worker keeps pulling and drains on idle-timeout.
	if signalComplete {
		p("# ---- signal spored (drives on_complete + spawn status --check-complete) ----\n")
		p("cat > /tmp/SPAWN_COMPLETE <<JSON\n")
		p("{\"status\": \"$STATE\", \"exit_code\": $rc, \"task_id\": %s}\n", jsonStr(taskID))
		p("JSON\n\n")
	}

	p("exit $rc\n")

	return b.String()
}

// PhaseTimestampFormat is the `date` format of the wrapper's spawn_phase
// markers in command.log: UTC with milliseconds, e.g. 2026-10-20T16:28:51.123Z
// (#1072). %3N needs GNU date, which AL2023 ships.
const PhaseTimestampFormat = "+%Y-%m-%dT%H:%M:%S.%3NZ"

// s3Cp is how every wrapper copy to or from S3 starts (#1072). --no-progress
// drops the \r-separated progress meter, about 20 lines per file of a
// multi-MB object, which buried the task's own output and the phase markers in
// command.log. It keeps the one "download:/upload:" line per file and every
// error, unlike --only-show-errors, so the log still says what was staged.
const s3Cp = "aws s3 cp --no-progress"

// writeDockerInstallStart starts a container task's Docker install in the
// background, before stage-in, so the two overlap (#1072). Measured in E1
// (spawn#1171) the install takes ~66 s and is paid on every launch; input
// staging is usually shorter, so a task's wait before `docker pull` drops from
// install + staging to roughly the longer of the two.
//
// Only the package install moves. Its output goes to a file, printed in one
// block when writeContainerRun waits for it, so dnf's lines do not interleave
// with staging's in command.log. Its exit status is the subshell's: dnf's, or 0
// when Docker is already present. Starting the daemon, the GPU toolkit and the
// pull stay after the wait, in order.
//
// The overlap means dnf and `aws s3 cp` now share memory. At the 2 GiB
// container floor that is expected to fit, but it is not measured; if dnf is
// OOM-killed the task fails as instance_health (retryable), as it did inline.
func writeDockerInstallStart(p func(string, ...interface{})) {
	p("# ---- container runtime: install Docker in the background, overlapping stage-in (#1072) ----\n")
	p("spawn_phase 'docker install start'\n")
	p("DOCKER_INSTALL_LOG=\"${TMPDIR:-/tmp}/spawn-docker-install.$$.log\"\n")
	p("(\n")
	p("  if ! command -v docker >/dev/null 2>&1; then\n")
	p("    echo 'spawn: installing docker...'\n")
	p("    sudo dnf install -y docker\n")
	p("  fi\n")
	p(") > \"$DOCKER_INSTALL_LOG\" 2>&1 &\n")
	p("DOCKER_INSTALL_PID=$!\n\n")
}

// quoteArgv single-quotes each argv element and joins with spaces, so the result
// can be placed inside `( … )` and run as a command without a shell re-parse.
func quoteArgv(argv []string) string {
	parts := make([]string, len(argv))
	for i, a := range argv {
		parts[i] = shQuote(a)
	}
	return strings.Join(parts, " ")
}

// writeContainerRun emits the container execution branch: install Docker on
// demand, log in to a private-ECR registry (public images skip login), pull the
// image, and run the argv inside it with the manifest dirs bind-mounted. Stage-in
// already put inputs on the host at those dirs; stage-out reads them back after —
// so the image needs no aws CLI. p writes into the wrapper; each line is indented
// to sit inside the `if [ "$STAGE_RC" -eq 0 ]; then` block.
func writeContainerRun(p func(string, ...interface{}), spec *TaskSpec, region string, gpu bool) {
	image := spec.Container

	// The command script runs as the unprivileged instance user (bootstrap runs it
	// via `su - <user>`), but installing Docker, managing its service, and talking
	// to the Docker socket all need root — so every privileged step here is sudo'd
	// (AL2023's default user has passwordless sudo). The host path never needs this.

	// Install Docker if absent (the task AMI is stock AL2023; no Docker baked in),
	// then make sure the daemon is up before we pull. Any failure here sets
	// RUNTIME_RC, skips the pull and run, and is classified instance_health
	// (#1180), never app_error: the user's command did not run. Before #1180
	// each step's failure was ignored, so an OOM-killed `dnf install docker`
	// fell through to `sudo docker run`, failed with "command not found", and
	// was blamed on the application.
	//
	// The install itself was started in the background before stage-in
	// (writeDockerInstallStart, #1072); this waits for it, so nothing below runs
	// before it has finished, and its exit status is RUNTIME_RC exactly as the
	// inline install's was.
	p("  spawn_phase 'docker install wait'\n")
	p("  wait \"$DOCKER_INSTALL_PID\" || RUNTIME_RC=$?\n")
	p("  cat \"$DOCKER_INSTALL_LOG\" 2>/dev/null || true\n")
	p("  rm -f \"$DOCKER_INSTALL_LOG\"\n")
	p("  if [ \"$RUNTIME_RC\" -eq 0 ]; then\n")
	p("    sudo systemctl enable --now docker || RUNTIME_RC=$?\n")
	p("  fi\n")
	// Wait for the socket (service start is async); bounded so we never hang. A
	// daemon that never answers is a runtime failure too.
	p("  if [ \"$RUNTIME_RC\" -eq 0 ]; then\n")
	p("    DOCKER_UP=0\n")
	p("    for _i in $(seq 1 30); do if sudo docker info >/dev/null 2>&1; then DOCKER_UP=1; break; fi; sleep 2; done\n")
	p("    if [ \"$DOCKER_UP\" -ne 1 ]; then echo 'spawn: docker daemon did not start' >&2; RUNTIME_RC=1; fi\n")
	p("  fi\n")
	p("  spawn_phase 'docker install done'\n")
	p("  if [ \"$RUNTIME_RC\" -ne 0 ]; then\n")
	p("    echo \"spawn: container runtime unavailable (rc=$RUNTIME_RC); skipping user command\" >&2\n")
	p("    rc=$RUNTIME_RC\n")
	p("  else\n")

	// GPU instances: `docker run --gpus all` needs the NVIDIA Container Toolkit as
	// a Docker runtime to bind-mount the host driver (incl. nvidia-smi) into the
	// container. The GPU DLAMI has the driver but AL2023's `dnf install docker`
	// does not include the toolkit, so without this the flag is a no-op and the
	// container sees no GPU (spawn#606). Install (if absent) + configure + restart
	// docker; all steps are idempotent, so a DLAMI that already ships the toolkit
	// just gets a re-configure. Only emitted for a GPU run.
	if gpu {
		p("  spawn_phase 'nvidia container toolkit start'\n")
		p("  if ! command -v nvidia-ctk >/dev/null 2>&1; then\n")
		p("    echo 'spawn: installing NVIDIA Container Toolkit...'\n")
		p("    curl -fsSL https://nvidia.github.io/libnvidia-container/stable/rpm/nvidia-container-toolkit.repo | sudo tee /etc/yum.repos.d/nvidia-container-toolkit.repo >/dev/null\n")
		p("    sudo dnf install -y nvidia-container-toolkit\n")
		p("  fi\n")
		p("  sudo nvidia-ctk runtime configure --runtime=docker\n")
		p("  sudo systemctl restart docker\n")
		p("  for _i in $(seq 1 30); do sudo docker info >/dev/null 2>&1 && break; sleep 2; done\n")
		p("  spawn_phase 'nvidia container toolkit done'\n")
	}

	// Private-ECR images need a docker login with the instance-role creds; public
	// images pull anonymously. ecrImageAccount!="" ⇒ private ECR ref.
	if ecrImageAccount(image) != "" {
		host := ecrRegistryHost(image)
		p("  echo 'spawn: authenticating to ECR (%s)...'\n", host)
		p("  aws ecr get-login-password --region %s | sudo docker login --username AWS --password-stdin %s\n",
			shQuote(region), shQuote(host))
	}

	// docker run --rm --user "$(id -u):$(id -g)" [--gpus all] <-v dir:dir ...>
	// <image> <argv>. rc is the container's exit code. All docker calls are
	// sudo'd (root owns the socket).
	//
	// --user "$(id -u):$(id -g)" (spawn#555): stage-in creates the bind-mounted
	// dirs as the instance user (uid 1000 on AL2023) with the default umask, so
	// they're 0755-owned by that uid. Without --user, the container runs as
	// whatever USER the image declares — and every bioconda/conda-forge image
	// (the entire mambaorg/micromamba-derived ecosystem) declares uid 57439
	// (mambauser), not root and not 1000. On real Linux, bind mounts preserve
	// host uid/gid, so that container gets EACCES writing into its own inputs
	// or outputs. Running the container as the invoking user's uid:gid instead
	// makes the container a packaging detail rather than a different security
	// context — it always matches whoever owns the staged dirs, regardless of
	// the image's declared USER.
	// --gpus all whenever the resolved instance is GPU-capable (gpu), not only when
	// spec.Resources.GPUs was explicitly set: a task sized onto a GPU box via
	// `families` (e.g. ["g5"]) still wants its GPU (spawn#601/#606). The toolkit
	// block above makes the flag actually attach the driver.
	gpuFlag := ""
	if gpu {
		gpuFlag = "--gpus all "
	}
	// Task env reaches the CONTAINER, not only the host shell (#1059). The
	// `export` block above sets it for the host wrapper; on its own it never
	// reached `docker run`, so a container task silently ran without it. Each
	// key is passed as one `-e KEY=VALUE` argv word holding the LITERAL value,
	// single-quoted:
	//   - not a bare `-e KEY`: sudo resets the environment by default, so
	//     docker would never see the exported value;
	//   - not `-e "KEY=$KEY"`: a key such as STAGE_RC or rc names a wrapper
	//     variable that is reassigned after the export, and the container
	//     would get the wrapper's value instead of the spec's.
	// Keys are shell identifiers (Validate rejects anything else), and the value
	// is inside single quotes, so neither can split the word or expand.
	var envFlags strings.Builder
	for _, k := range sortedKeys(spec.Env) {
		fmt.Fprintf(&envFlags, "-e %s ", shQuote(k+"="+spec.Env[k]))
	}
	var mounts strings.Builder
	for _, d := range containerMountDirs(spec) {
		fmt.Fprintf(&mounts, "-v %s:%s ", shQuote(d), shQuote(d))
	}
	p("  spawn_phase 'image pull start'\n")
	p("  sudo docker pull %s\n", shQuote(image))
	// The digest that actually ran, not what the tag pointed to (#1076).
	// The redirect runs as the wrapper's user on purpose: it created $PROV_DIR
	// above, and only docker needs root.
	p("  # shellcheck disable=SC2024  # $PROV_DIR is the wrapper user's own; only docker needs sudo\n")
	p("  if [ \"$PROV_OK\" = 1 ]; then sudo docker inspect --format '{{index .RepoDigests 0}}' %s > \"$PROV_DIR/image-digest\" 2>/dev/null || true; fi\n", shQuote(image))
	p("  spawn_phase 'image pull done; command start'\n")
	// --shm-size (#1111): Docker's 64 MB /dev/shm is too small for many-rank MPI
	// (SIGBUS in the first collective). Emitted only when resources.shm_gib is
	// set, and before the image: everything after the image is the container's
	// argv, so a flag placed there would be handed to the user's command instead.
	shmFlag := ""
	if f := shmSizeFlag(spec.Resources); f != "" {
		shmFlag = f + " "
	}
	p("  sudo docker run --rm --user \"$(id -u):$(id -g)\" %s%s%s%s%s %s\n", envFlags.String(), gpuFlag, shmFlag, mounts.String(), shQuote(image), quoteArgv(spec.Command))
	p("  rc=$?\n")
	p("  spawn_phase \"command exit rc=$rc\"\n")
	p("  fi\n") // closes the RUNTIME_RC guard opened after the Docker install
}

// manifestMountDirs returns the distinct host directories the wrapper's own
// stage-in/stage-out loops populate: the parent dir of each input Destination
// and each output Source (identity-mounted, so in-container paths match the
// argv the spec author wrote). Sorted for a stable wrapper; "/", "." and
// empty are skipped.
//
// The stage-in mkdir loop (above, in generateWrapper) iterates this SAME
// set — deliberately reusing this function's output rather than recomputing
// "what needs a mkdir" independently — so every manifest directory that gets
// bind-mounted also gets pre-created, as the invoking user, before `docker
// run` runs (spawn#564). Previously only input destination parents got an
// explicit `mkdir -p`; an output whose parent wasn't shared with any input
// was left for `docker run -v` to auto-create — which dockerd does as root,
// mode 0755, so the non-root container then got EACCES on its first write.
//
// This function intentionally does NOT include Placement's EFS/FSx/volume
// mount points (spawn#570) — see containerMountDirs below for the superset
// that does, and the comment on the mkdir loop in generateWrapper for why
// mkdir'ing a placement mount point would be actively harmful, not just
// redundant.
func manifestMountDirs(spec *TaskSpec) []string {
	seen := map[string]bool{}
	var dirs []string
	add := func(p string) {
		d := path.Dir(p)
		if d == "" || d == "." || d == "/" || seen[d] {
			return
		}
		seen[d] = true
		dirs = append(dirs, d)
	}
	for _, m := range spec.Inputs {
		add(m.Destination)
	}
	for _, m := range spec.Outputs {
		add(m.Source)
	}
	sort.Strings(dirs)
	return dirs
}

// containerMountDirs returns the distinct host directories to bind-mount into
// the container via `docker run -v`: manifestMountDirs (manifest-derived
// input/output parents) PLUS every Placement mount point the spec's boot-time
// storage script (pkg/tasklaunch's taskStorageScript) already mounted on the
// host — each Placement.Volumes[].MountPath, the EFS mount point (when
// Placement.EFSID is set), and the FSx mount point (when
// Placement.FSxLustreID is set). Sorted for a stable wrapper; "/", "." and
// empty are skipped; duplicates (e.g. a volume mounted under a manifest dir)
// are deduped.
//
// Before spawn#570, writeContainerRun's `docker run -v` list was built from
// manifestMountDirs alone: a container task with an EFS/FSx/volume placement
// but no manifest entry under that path got the filesystem mounted on the
// HOST (taskStorageScript genuinely runs and mounts it) but never bind-mounted
// INTO the container — every containerized task (the aarch.bio/aarch.science
// one-tool-per-image model runs Container != "" for EVERY task) silently lost
// access to placement storage that a host-argv task (Container == "") would
// have seen for free. This function is now the single "what does the
// container get to see" superset; manifestMountDirs stays the narrower "what
// does stage-in need to mkdir" set (see the mkdir loop's comment for why the
// two must NOT be merged back into one list).
func containerMountDirs(spec *TaskSpec) []string {
	dirs := manifestMountDirs(spec)
	seen := map[string]bool{}
	for _, d := range dirs {
		seen[d] = true
	}
	add := func(d string) {
		d = strings.TrimSuffix(d, "/")
		if d == "" || d == "." || d == "/" || seen[d] {
			return
		}
		seen[d] = true
		dirs = append(dirs, d)
	}
	p := spec.Placement
	for _, v := range p.Volumes {
		add(v.MountPath)
	}
	if p.EFSID != "" {
		add(p.EffectiveEFSMountPoint())
	}
	if p.FSxLustreID != "" {
		add(p.EffectiveFSxMountPoint())
	}
	sort.Strings(dirs)
	return dirs
}

// recursiveFlag returns " --recursive" when an S3/dir source is a prefix
// (trailing slash), matching `aws s3 cp` semantics for copying a whole prefix.
func recursiveFlag(source string) string {
	if strings.HasSuffix(source, "/") {
		return " --recursive"
	}
	return ""
}

// recursiveChownFlag returns " -R" for a prefix source (spawn#565): a
// "--recursive" `aws s3 cp` populates a whole tree under Destination, so the
// post-stage chown must walk it too, not just chown the top-level path.
func recursiveChownFlag(source string) string {
	if strings.HasSuffix(source, "/") {
		return " -R"
	}
	return ""
}

// ecrImageAccount returns the AWS account owning a private-ECR image, or "" if
// the image isn't a private-ECR ref (e.g. a public quay.io/docker.io image).
// Thin alias over pkg/ecrref, kept so callers in this file read the same as
// before (was a taskproto-local duplicate of cmd/app_byo.go's helper — now
// shared via the leaf, not copy-pasted a third time).
func ecrImageAccount(image string) string { return ecrref.Account(image) }

// ecrRegistryHost returns the registry host (everything before the first '/') —
// the argument `docker login` expects. Thin alias over pkg/ecrref.
func ecrRegistryHost(image string) string { return ecrref.RegistryHost(image) }

// shQuote wraps s in single quotes, escaping embedded single quotes. This is the
// safe form for shell interpolation (unlike strconv.Quote, which uses
// double-quote semantics and would expand $ and backticks). Copied from the
// pattern in pkg/pluginruntime/remote_executor.go rather than reusing
// security.ShellEscape.
func shQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "'\\''") + "'"
}

// jsonStr renders a Go string as a JSON string literal (with surrounding quotes),
// used for the few values interpolated into the heredoc'd completion record.
func jsonStr(s string) string {
	// Escape the characters that matter inside a double-quoted JSON string.
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\t", `\t`, "\r", `\r`)
	return `"` + r.Replace(s) + `"`
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// writeProvenanceSetup emits the provenance preamble (#1076). PROV_OK=1 only
// when spored is present AND has the provenance subcommand. A new wrapper can
// meet an older spored, and there `spored provenance upload` would exit
// "unknown command" and fail the output upload, so everything falls back to
// plain `aws s3 cp` unless the subcommand answers. The spec copy has env VALUES
// stripped: they can hold secrets, and the record keeps names only.
func writeProvenanceSetup(p func(string, ...interface{}), spec *TaskSpec, runID string) {
	dirID := runID
	if dirID == "" {
		dirID = spec.TaskID
	}
	// SPAWN_SPORED_BIN exists for the wrapper's own execution tests; nothing sets
	// it on an instance.
	p("SPORED=\"${SPAWN_SPORED_BIN:-/usr/local/bin/spored}\"\n")
	p("PROV_DIR=%s\n", shQuote("/tmp/spawn-provenance/"+safePathPart(dirID)))
	p("PROV_OK=0\n")
	p("if [ -x \"$SPORED\" ] && \"$SPORED\" provenance --help >/dev/null 2>&1 && mkdir -p \"$PROV_DIR\" 2>/dev/null; then\n")
	p("  cat > \"$PROV_DIR/spec.json\" <<'SPAWN_PROVENANCE_SPEC'\n%s\nSPAWN_PROVENANCE_SPEC\n", provenanceSpecJSON(spec))
	p("  [ -s \"$PROV_DIR/spec.json\" ] && PROV_OK=1\n")
	p("fi\n\n")
}

// provenanceSpecJSON is the spec as the provenance record sees it: env values
// blanked, names kept. One line, so it can never equal the heredoc delimiter.
func provenanceSpecJSON(spec *TaskSpec) string {
	cp := *spec
	if len(spec.Env) > 0 {
		cp.Env = make(map[string]string, len(spec.Env))
		for k := range spec.Env {
			cp.Env[k] = ""
		}
	}
	b, err := json.Marshal(&cp)
	if err != nil {
		return "{}"
	}
	return string(b)
}

// safePathPart keeps an id usable as one path segment.
func safePathPart(id string) string {
	var b strings.Builder
	for _, r := range id {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_', r == '.':
			b.WriteRune(r)
		default:
			b.WriteRune('_')
		}
	}
	if b.Len() == 0 {
		return "run"
	}
	return b.String()
}

// imdsBase is the instance metadata service the wrapper asks for its instance
// type and life cycle. A generate-time value, like localRecordDir, so the
// exec-based tests of this package and pkg/taskpool can point it at loopback:
// under the hermetic test wrapper (#968) a request to the real address goes to
// the recorder and fails the package.
var imdsBase = "http://169.254.169.254/latest"

// SetIMDSBaseForTest points the generated wrapper's IMDS lookups at base (the
// part before /api/token and /meta-data/) for the rest of this test binary's
// run, and returns a function restoring the previous value. Exported for
// pkg/taskpool's exec tests, as SetLocalRecordDirForTest is.
func SetIMDSBaseForTest(base string) (restore func()) {
	prev := imdsBase
	imdsBase = base
	return func() { imdsBase = prev }
}

// writeInstanceFacts emits the IMDS lookup that fills completion.json's
// instance_type and purchase (spawn#1260): INSTANCE_JSON is those two members,
// each with its trailing comma, or nothing for one IMDS did not answer. It is
// also persisted to instanceFactsPath for the terminal-flush hook, which runs
// against a deadline and so does not ask IMDS itself.
//
// IMDSv2 only, as spawn launches require it. Best-effort and bounded: off EC2,
// or with IMDS unreachable, the token request gives up after one second, the
// two reads are skipped, and the record omits the fields rather than guessing. Only a plain instance type
// ([a-z0-9.-]) and a life cycle of exactly spot or on-demand reach the record,
// so no IMDS answer can break the completion.json heredoc.
//
// Kept terse on purpose: every byte here rides in the instance's user data,
// which EC2 caps at 16 KiB after gzip (spawn#1063).
func writeInstanceFacts(p func(string, ...interface{})) {
	p("IMDS_TOKEN=\"$(curl -sfm1 -XPUT %s -H 'X-aws-ec2-metadata-token-ttl-seconds: 60' 2>/dev/null)\"\n", imdsBase+"/api/token")
	p("imds() { [ -n \"$IMDS_TOKEN\" ] && curl -sfm1 -H \"X-aws-ec2-metadata-token: $IMDS_TOKEN\" \"%s/meta-data/$1\" 2>/dev/null; }\n", imdsBase)
	p("INSTANCE_JSON=''; IT=\"$(imds instance-type)\"\n")
	p("case \"$IT\" in ''|*[!a-z0-9.-]*) ;; *) INSTANCE_JSON=\"\\\"instance_type\\\": \\\"$IT\\\",\" ;; esac\n")
	p("case \"$(imds instance-life-cycle)\" in\n")
	p("  spot) INSTANCE_JSON=\"$INSTANCE_JSON \\\"purchase\\\": \\\"%s\\\",\" ;;\n", PurchaseSpot)
	p("  on-demand) INSTANCE_JSON=\"$INSTANCE_JSON \\\"purchase\\\": \\\"%s\\\",\" ;;\n", PurchaseOnDemand)
	p("esac\n")
	p("printf '%%s' \"$INSTANCE_JSON\" > %s 2>/dev/null\n\n", shQuote(instanceFactsPath()))
}
