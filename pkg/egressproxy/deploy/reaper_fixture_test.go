var updateReaperFixture = flag.Bool("update", false, "rewrite "+reaperFixturePath+" from the producers")

// reaperFixturePath is where the TTL reaper's tests read the proxy's tags
// from. The reaper is its own module and does not import this package (it
// would pull the whole CLI's dependency tree into a deployed Lambda), so the
// tags cross as a generated file instead, regenerated and checked here.
const reaperFixturePath = "../../../lambda/ttl-reaper/testdata/egress_proxy_tags.json"

// ReaperFixture is the proxy's tag set as its producers write it.
type reaperFixture struct {
	Comment      string            `json:"comment"`
	LaunchTime   string            `json:"launch_time"`
	Deadline     string            `json:"deadline"`
	InstanceTags map[string]string `json:"instance_tags"`
	VolumeTags   map[string]string `json:"volume_tags"`
	Groups       []fixtureGroup    `json:"groups"`
}

type fixtureGroup struct {
	Name string            `json:"name"`
	Tags map[string]string `json:"tags"`
	// References is the group its ingress rules name, if any: EC2 refuses to
	// delete a group another group's rule references.
	References string `json:"references,omitempty"`
}

// buildReaperFixture runs the real producers against the fake: pkg/aws's
// launch tag builder for the base tags (as ClientFor does), Create's
// RunInstances request, and EnsureGroups's CreateSecurityGroup requests.
func buildReaperFixture(t *testing.T) []byte {
	t.Helper()
	const version = "0.0.0-fixture"
	base, err := spawnaws.BuildLaunchTags(LaunchConfig("us-west-2", version), "123456789012",
		"arn:aws:iam::123456789012:user/fixture", "")
	if err != nil {
		t.Fatal(err)
	}
	// Anchor the launch at t0 so the file does not change with the clock.
	if base, err = spawnaws.AnchorLaunchTags(base, t0); err != nil {
		t.Fatal(err)
	}
	f := &fakeEC2{}
	g, err := EnsureGroups(context.Background(), f, testVPC, t0)
	if err != nil {
		t.Fatal(err)
	}
	p, err := Create(context.Background(), Deps{EC2: f, Now: func() time.Time { return t0 }}, Spec{
		Region: "us-west-2", VPCID: testVPC, AvailabilityZone: "us-west-2a",
		PublicSubnets: []spawnaws.PublicSubnet{{SubnetID: "subnet-pub", AvailabilityZone: "us-west-2a"}},
		Groups:        g, AMI: "ami-0123456789abcdef0", InstanceProfile: testProfile, UserData: "ud", BaseTags: base,
	})
	if err != nil {
		t.Fatal(err)
	}
	in := f.runInputs[0]
	fx := reaperFixture{
		Comment:      "GENERATED by pkg/egressproxy/deploy TestReaperFixtureIsCurrent (go test ./pkg/egressproxy/deploy -run TestReaperFixtureIsCurrent -update). Do not edit.",
		LaunchTime:   p.LaunchTime.UTC().Format(time.RFC3339),
		Deadline:     p.Deadline.UTC().Format(time.RFC3339),
		InstanceTags: tagMap(in.TagSpecifications[0].Tags),
		VolumeTags:   tagMap(in.TagSpecifications[1].Tags),
	}
	for _, sg := range f.groups {
		fg := fixtureGroup{Name: aws.ToString(sg.GroupName), Tags: tagMap(sg.Tags)}
		for _, r := range rulesOf(sg.IpPermissions) {
			if r.group == g.ClientsID {
				fg.References = ClientsGroupName(testVPC)
			}
		}
		fx.Groups = append(fx.Groups, fg)
	}
	b, err := json.MarshalIndent(fx, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return append(b, '\n')
}

// The reaper's tests of the proxy (lambda/ttl-reaper egress_proxy_test.go)
// read the tags its producers actually write, not a copy (#1515 phase 5).
// This fails when the producers change and the file was not regenerated.
func TestReaperFixtureIsCurrent(t *testing.T) {
	got := buildReaperFixture(t)
	if *updateReaperFixture {
		if err := os.WriteFile(filepath.FromSlash(reaperFixturePath), got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(filepath.FromSlash(reaperFixturePath))
	if err != nil {
		t.Fatalf("%v; generate it with -update", err)
	}
	if !bytes.Equal(bytes.ReplaceAll(want, []byte("\r\n"), []byte("\n")), got) {
		t.Errorf("%s is stale: the proxy's tags changed. Regenerate it with "+
			"`go test ./pkg/egressproxy/deploy -run TestReaperFixtureIsCurrent -update` "+
			"and run the reaper's tests (cd lambda/ttl-reaper && go test ./...)", reaperFixturePath)
	}
	var fx reaperFixture
	if err := json.Unmarshal(got, &fx); err != nil {
		t.Fatal(err)
	}
	// What the reaper selects on must be in it, or its tests prove nothing.
	if fx.InstanceTags["spawn:managed"] != "true" || fx.InstanceTags["spawn:ttl-deadline"] != fx.Deadline ||
		fx.InstanceTags[ProxyTag] != testVPC || len(fx.Groups) != 2 {
		t.Errorf("fixture lacks what the reaper selects on: %+v", fx)
	}
	if want := t0.Add(egressproxy.MaxLife).Format(time.RFC3339); fx.Deadline != want {
		t.Errorf("fixture deadline %s, want launch plus the proxy's life, %s", fx.Deadline, want)
	}
}
